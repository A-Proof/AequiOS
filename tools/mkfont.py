#!/usr/bin/env python3
"""Convert a Linux console font (PSF1 or PSF2) into kernel C source.

Usage: mkfont.py <out.c> [psf.gz]
Default font: /usr/share/consolefonts/Lat15-Terminus16.psf.gz (8x16 PSF1)
"""
import gzip
import struct
import sys

FONT_PATH = "/usr/share/consolefonts/Lat15-Terminus16.psf.gz"


def load_font(path: str):
    with gzip.open(path, "rb") as f:
        data = f.read()
    magic = struct.unpack_from("<I", data, 0)[0]
    if magic & 0xFFFF == 0x0436:            # PSF1
        mode, charsize = data[2], data[3]
        nglyphs = 512 if (mode & 1) else 256
        return data, 4, nglyphs, charsize, charsize, 8
    if magic == 0x864AB572:                 # PSF2
        (_magic, _version, headersize, _flags, nglyphs,
         bpg, height, width) = struct.unpack_from("<8I", data, 0)
        if height != 16 or width != 8:
            raise SystemExit(f"{path}: need an 8x16 font, got {width}x{height}")
        return data, headersize, nglyphs, bpg, height, width
    raise SystemExit(f"{path}: unknown font format (magic {magic:#x})")


def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else "font_data.c"
    path = sys.argv[2] if len(sys.argv) > 2 else FONT_PATH
    data, off, nglyphs, bpg, height, _w = load_font(path)

    rows = []
    for g in range(32, 127):
        glyph = data[off + g * bpg: off + (g + 1) * bpg]
        rows.append(", ".join(f"0x{b:02x}" for b in glyph[:height]))

    with open(out, "w") as f:
        f.write("/* generated by tools/mkfont.py from %s */\n" % path)
        f.write("const unsigned char font_data[95][16] = {\n")
        for r in rows:
            f.write("    {%s},\n" % r)
        f.write("};\n")
    print(f"font: {nglyphs} glyphs from {path} → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
