/* Aura v0 — framebuffer console + boot splash.
 * Deep-navy background, calm typography, thin teal accent.
 *
 * The console renders inside a settable rectangle (`fb_set_console_rect`)
 * and keeps a text grid backing so the desktop can repaint the region
 * after moving a window. */
#include <kernel.h>

#define FONT_W 8
#define FONT_H 16

extern const u8 font_data[95][FONT_H];   /* generated by tools/mkfont.py */

extern volatile struct limine_framebuffer_request framebuffer_request;

static volatile u32 *fb;
static u64 fb_w, fb_h, fb_pitch;         /* pitch in pixels */
static u32 fg = 0xFFE8ECF1, bg = 0xFF0E1420, accent = 0xFF2BB3A3;
static int cx, cy;
static int cols, rows;
static int con_x, con_y, con_w, con_h;   /* console rect, pixels */
static char *con_grid;                   /* cols*rows text backing */
static u32 *con_surf;                    /* console's own pixel surface */
static bool con_dirty;

/* retargetable draw destination: the real fb, or an app surface the
 * compositor blits later. px()/fb_get() always write to g_dst. */
static u32 *g_dst;
static u64 g_pitch_px, g_w, g_h;

static void dst_fb(void) {
    g_dst = (u32 *)fb; g_pitch_px = fb_pitch; g_w = fb_w; g_h = fb_h;
}

void fb_dst_set(u32 *pix, u64 pitch, u64 w, u64 h) {
    if (!pix) { dst_fb(); return; }
    g_dst = pix; g_pitch_px = pitch; g_w = w; g_h = h;
}

void px(int x, int y, u32 c) {
    if (!g_dst || x < 0 || y < 0 || (u64)x >= g_w || (u64)y >= g_h) return;
    g_dst[y * g_pitch_px + x] = c;
}

u32 fb_get(int x, int y) {
    if (!g_dst || x < 0 || y < 0 || (u64)x >= g_w || (u64)y >= g_h) return 0;
    return g_dst[y * g_pitch_px + x];
}

void fb_fill_rect(int x, int y, int w, int h, u32 c) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            px(x + i, y + j, c);
}

static void glyph_at(int x, int y, char c, u32 color, int scale) {
    int g = (unsigned char)c - 32;
    if (g < 0 || g >= 95) g = '?' - 32;
    fb_fill_rect(x, y, FONT_W * scale, FONT_H * scale, bg);
    for (int row = 0; row < FONT_H; row++) {
        u8 bits = font_data[g][row];
        for (int col = 0; col < FONT_W; col++)
            if (bits & (0x80 >> col))
                fb_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
    }
}

void fb_text(int x, int y, const char *s, u32 color, int scale) {
    for (; *s; s++) { glyph_at(x, y, *s, color, scale); x += FONT_W * scale; }
}

static int text_width(const char *s, int scale) {
    return (int)strlen(s) * FONT_W * scale;
}

u64 fb_width(void)  { return fb_w; }
u64 fb_height(void) { return fb_h; }
bool fb_ready(void) { return fb != NULL; }

/* console output goes to con_surf when it exists (the terminal window's
 * retained surface); the x,y rect is then surface-local (0,0). When the
 * surface allocation failed we fall back to drawing straight into the fb
 * at the caller's rect. */
static void con_target(void) {
    if (con_surf) fb_dst_set(con_surf, (u64)con_w, (u64)con_w, (u64)con_h);
    else          dst_fb();
}

static void scroll_if_needed(void) {
    if (cy < rows) return;
    memmove(con_grid, con_grid + cols, (size_t)cols * (rows - 1));
    for (int x = 0; x < cols; x++)
        con_grid[(rows - 1) * cols + x] = ' ';
    fb_repaint();           /* pixels always mirror the grid */
    cy = rows - 1;
}

void fb_repaint(void) {
    if (!con_grid) return;
    con_target();
    for (int r = 0; r < rows; r++)
        for (int c = 0; c < cols; c++)
            glyph_at(con_x + c * FONT_W, con_y + r * FONT_H,
                     con_grid[r * cols + c], fg, 1);
    dst_fb();
    con_dirty = true;
}

/* compositor view of the console surface; NULL when not available */
u32 *fb_console_surface(int *pitch, int *w, int *h) {
    if (!con_surf) return NULL;
    if (pitch) *pitch = con_w;
    if (w) *w = con_w;
    if (h) *h = con_h;
    return con_surf;
}

bool fb_console_dirty(void) { return con_dirty; }
void fb_console_clean(void) { con_dirty = false; }

void fb_set_console_rect(int x, int y, int w, int h) {
    con_w = w; con_h = h;
    cols = w / FONT_W;
    rows = h / FONT_H;
    if (!con_grid)
        con_grid = kmalloc(128 * 48);
    if (!con_surf) {
        con_surf = kmalloc((size_t)w * h * 4);
        if (con_surf) memset(con_surf, 0, (size_t)w * h * 4);
    }
    if (con_surf) { con_x = 0; con_y = 0; }       /* surface-local */
    else          { con_x = x; con_y = y; }       /* fb fallback   */
    memset(con_grid, ' ', (size_t)cols * rows);
    cx = cy = 0;
}

void fb_putc(char c) {
    if (!con_grid) return;
    if (c == '\n') { cx = 0; cy++; scroll_if_needed(); return; }
    if (c == '\r') { cx = 0; return; }
    if (c == '\t') { cx = (cx + 8) & ~7; if (cx >= cols) { cx = 0; cy++; } scroll_if_needed(); return; }
    if (c == '\b') {
        if (cx) {
            cx--;
            con_grid[cy * cols + cx] = ' ';
            con_target();
            glyph_at(con_x + cx * FONT_W, con_y + cy * FONT_H, ' ', fg, 1);
            dst_fb();
            con_dirty = true;
        }
        return;
    }
    if (cx >= cols) { cx = 0; cy++; }
    scroll_if_needed();          /* internally: con_target .. dst_fb */
    con_target();
    con_grid[cy * cols + cx] = c;
    glyph_at(con_x + cx * FONT_W, con_y + cy * FONT_H, c, fg, 1);
    cx++;
    dst_fb();
    con_dirty = true;
}

void fb_init(void) {
    struct limine_framebuffer_response *r = framebuffer_request.response;
    if (!r || r->framebuffer_count == 0) {
        early_printk("fb: none available\n");
        return;
    }
    struct limine_framebuffer *f = r->framebuffers[0];
    fb = f->address;
    fb_w = f->width;
    fb_h = f->height;
    fb_pitch = f->pitch / 4;             /* bytes → pixels (32bpp) */
    dst_fb();
    early_printk("fb: %llux%llu pitch=%llu bpp=%u\n",
                 (unsigned long long)fb_w, (unsigned long long)fb_h,
                 (unsigned long long)f->pitch, f->bpp);
}

void fb_splash(void) {
    if (!fb) return;
    fb_fill_rect(0, 0, (int)fb_w, (int)fb_h, bg);

    const char *title = "AequiOS";
    int scale = (fb_w > 900) ? 5 : 3;
    int tw = text_width(title, scale);
    int tx = ((int)fb_w - tw) / 2;
    int ty = (int)fb_h / 5;
    fb_text(tx, ty, title, 0xFFE8ECF1, scale);
    /* teal 'OS' */
    fb_text(tx + text_width("Aequi", scale), ty, "OS", accent, scale);

    const char *sub = "Even in Architecture, Design, and Spirit";
    fb_text(((int)fb_w - text_width(sub, 1)) / 2, ty + FONT_H * scale + 12, sub, 0xFF9AA7B4, 1);

    /* accent rule */
    int rule_w = (int)fb_w / 3;
    fb_fill_rect(((int)fb_w - rule_w) / 2, ty + FONT_H * scale + 44, rule_w, 2, accent);

    fb_set_console_rect(0, ty + FONT_H * scale + 72, (int)fb_w,
                        (int)fb_h - (ty + FONT_H * scale + 72));
}
